def build():
    print("Building clean database...")
    conn = sqlite3.connect("village_fund.db")
    c = conn.cursor()

    # Drop old tables
    c.execute("DROP TABLE IF EXISTS tb_members")
    c.execute("DROP TABLE IF EXISTS tb_payments")
    c.execute("DROP TABLE IF EXISTS tb_expenses")
    c.execute("DROP TABLE IF EXISTS tb_summary_config")

    # 1. tb_members
    c.execute("""
    CREATE TABLE tb_members (
        member_id INTEGER PRIMARY KEY,
        alley TEXT NOT NULL,
        house_no TEXT NOT NULL UNIQUE,
        owner_name TEXT NOT NULL,
        monthly_rate REAL NOT NULL,
        annual_target REAL NOT NULL,
        remark TEXT
    )
    """)

    # 2. tb_payments (Transaction-based ledger)
    c.execute("""
    CREATE TABLE tb_payments (
        payment_id TEXT PRIMARY KEY,
        payment_date TEXT NOT NULL,
        house_no TEXT NOT NULL,
        payer_name TEXT NOT NULL,
        quarters_paid TEXT NOT NULL,
        months_paid TEXT NOT NULL,
        amount REAL NOT NULL,
        channel TEXT NOT NULL,
        recorded_by TEXT NOT NULL,
        remark TEXT,
        FOREIGN KEY (house_no) REFERENCES tb_members(house_no)
    )
    """)

    # 3. tb_expenses
    c.execute("""
    CREATE TABLE tb_expenses (
        doc_no TEXT PRIMARY KEY,
        expense_date TEXT NOT NULL,
        category TEXT NOT NULL,
        title TEXT NOT NULL,
        amount REAL NOT NULL,
        payee TEXT NOT NULL,
        paid_from TEXT NOT NULL,
        status TEXT NOT NULL
    )
    """)

    # 4. tb_summary_config
    c.execute("""
    CREATE TABLE tb_summary_config (
        key TEXT PRIMARY KEY,
        value REAL NOT NULL,
        description TEXT
    )
    """)

    # Insert members & their existing payment transactions
    payment_counter = 1
    total_initial_collected = 0.0

    for idx, (alley, row_no, name, house_no, rate, months, note) in enumerate(MEMBERS_DATA, 1):
        annual_target = rate * 12
        c.execute("""
            INSERT INTO tb_members (member_id, alley, house_no, owner_name, monthly_rate, annual_target, remark)
            VALUES (?, ?, ?, ?, ?, ?, ?)
        """, (idx, alley, house_no, name, rate, annual_target, note))

        paid_amount = sum(months)
        if paid_amount > 0:
            total_initial_collected += paid_amount
            # Determine which quarters are paid
            q_list = []
            if sum(months[0:3]) > 0: q_list.append("งวด 1")
            if sum(months[3:6]) > 0: q_list.append("งวด 2")
            if sum(months[6:9]) > 0: q_list.append("งวด 3")
            if sum(months[9:12]) > 0: q_list.append("งวด 4")
            q_str = ", ".join(q_list)

            # Month indices that were paid
            paid_m_indices = [i+1 for i, m in enumerate(months) if m > 0]

            rec_no = f"REC-69-{payment_counter:04d}"
            payment_counter += 1

            c.execute("""
                INSERT INTO tb_payments (payment_id, payment_date, house_no, payer_name, quarters_paid, months_paid, amount, channel, recorded_by, remark)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """, (rec_no, "2026-01-15", house_no, name, q_str, json.dumps(paid_m_indices), paid_amount, "ธนาคาร", "ระบบตั้งต้น", note))

    # Insert expenses
    total_expenses = 0.0
    for doc_no, exp_date, cat, title, amt, payee, stat in EXPENSES_DATA:
        total_expenses += amt
        paid_from = "เงินสดสำรอง" if "สำรอง" in title or amt < 5000 and "รปภ" not in cat else "บัญชีธนาคาร"
        c.execute("""
            INSERT INTO tb_expenses (doc_no, expense_date, category, title, amount, payee, paid_from, status)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?)
        """, (doc_no, exp_date, cat, title, amt, payee, paid_from, stat))

    # Insert summary config
    configs = [
        ("initial_balance_2568", 82969.73, "ยอดเงินคงเหลือปี 2568 (ณ 24 ม.ค. 69) ยกมา"),
        ("initial_reserve_cash", 10049.57, "ยอดเงินสดสำรอง ยกมาจากปี 2568"),
        ("support_income", 168.39, "เงินสนับสนุน / ดอกเบี้ยรับปี 2569"),
        ("current_cash_reserve", 13764.47, "เงินสำรองคงเหลือ (เงินสด) ปัจจุบัน"),
        ("current_bank_balance", 54353.55, "เงินคงเหลือในสมุดบัญชีธนาคาร ปัจจุบัน"),
        ("total_ending_balance", 68118.02, "รวมเงินคงเหลือทั้งหมด (เงินสด + ธนาคาร)")
    ]
    for k, v, desc in configs:
        c.execute("INSERT INTO tb_summary_config (key, value, description) VALUES (?, ?, ?)", (k, v, desc))

    # Also maintain materialized 'members' table for ultra-fast dashboard queries
    c.execute("DROP TABLE IF EXISTS members")
    c.execute("""
    CREATE TABLE members (
        id INTEGER PRIMARY KEY,
        row_no INTEGER,
        alley TEXT NOT NULL,
        house_no TEXT NOT NULL,
        name TEXT NOT NULL,
        fee_monthly REAL NOT NULL,
        m1 REAL, m2 REAL, m3 REAL, m4 REAL, m5 REAL, m6 REAL,
        m7 REAL, m8 REAL, m9 REAL, m10 REAL, m11 REAL, m12 REAL,
        q1_total REAL, q2_total REAL, q3_total REAL, q4_total REAL,
        year_total REAL, due_amount REAL, status TEXT, remark TEXT
    )
    """)

    for idx, (alley, row_no, name, house_no, rate, months, note) in enumerate(MEMBERS_DATA, 1):
        q1 = sum(months[0:3])
        q2 = sum(months[3:6])
        q3 = sum(months[6:9])
        q4 = sum(months[9:12])
        year_total = sum(months)
        annual_target = rate * 12
        due = max(0.0, annual_target - year_total)
        status = "ชำระครบทั้งปี" if year_total >= annual_target else ("ชำระบางส่วน" if year_total > 0 else "ยังไม่ชำระ")
        c.execute("""
            INSERT INTO members (id, row_no, alley, house_no, name, fee_monthly,
                                 m1, m2, m3, m4, m5, m6, m7, m8, m9, m10, m11, m12,
                                 q1_total, q2_total, q3_total, q4_total, year_total, due_amount, status, remark)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """, (idx, idx, alley, house_no, name, rate, *months, q1, q2, q3, q4, year_total, due, status, note))

    # Also maintain 'expenses' table
    c.execute("DROP TABLE IF EXISTS expenses")
    c.execute("""
    CREATE TABLE expenses (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        doc_no TEXT,
        date TEXT,
        category TEXT,
        title TEXT,
        amount REAL,
        payee TEXT,
        status TEXT
    )
    """)
    for doc_no, exp_date, cat, title, amt, payee, stat in EXPENSES_DATA:
        c.execute("""
            INSERT INTO expenses (doc_no, date, category, title, amount, payee, status)
            VALUES (?, ?, ?, ?, ?, ?, ?)
        """, (doc_no, exp_date, cat, title, amt, payee, stat))

    # Also maintain 'bank_transactions' table
    c.execute("DROP TABLE IF EXISTS bank_transactions")
    c.execute("""
    CREATE TABLE bank_transactions (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        date TEXT,
        house_no TEXT,
        alley TEXT,
        description TEXT,
        income REAL,
        expense REAL,
        balance REAL,
        transfer_time TEXT
    )
    """)
    c.execute("""
        INSERT INTO bank_transactions (date, house_no, alley, description, income, expense, balance, transfer_time)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?)
    """, ("15/01/69", "-", "-", "ยอดยกมาจากปี 2568", 82969.73, 0.0, 54353.55, "09.00"))

    conn.commit()
